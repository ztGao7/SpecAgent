"""Visual DREAM-R adapter control flow; no model services are needed to test it."""
import copy
import threading
import time
from dataclasses import asdict, dataclass, field
from typing import Optional


class BudgetExceeded(RuntimeError):
    pass


class ProtocolError(RuntimeError):
    pass


class InfrastructureError(RuntimeError):
    """A service/transport failure must stop a run, not become mass wrong rows."""


@dataclass(frozen=True)
class Config:
    threshold: int = 7
    max_turns: int = 8
    max_tokens: int = 4096
    max_tool_calls: int = 8
    max_total_output_tokens: int = 0  # 0 = no total cap, explicitly reported
    wall_seconds: float = 0.0
    max_image_history: int = 5
    mode: str = "dreamr"  # also supports matched neutral Main/Draft-only
    accept_threshold: float = 0.7  # dreamr (TBVM): P(positive) needed to accept a draft turn
    first_main_turns: int = 0      # dreamr: leading turns generated by Main only

    def __post_init__(self):
        if not 0 <= self.threshold <= 9:
            raise ValueError("threshold must be in 0..9")
        if min(self.max_turns, self.max_tokens, self.max_image_history) < 1:
            raise ValueError("turn/token/image limits must be positive")
        if min(self.max_tool_calls, self.max_total_output_tokens, self.wall_seconds) < 0:
            raise ValueError("budgets must be non-negative")
        if self.mode not in {"specreason", "dreamr", "main-only", "draft-only"}:
            raise ValueError("unsupported mode")
        if not 0.0 <= self.accept_threshold <= 1.0 or self.first_main_turns < 0:
            raise ValueError("accept_threshold must be in [0, 1]; first_main_turns non-negative")


@dataclass
class Turn:
    message: dict
    calls: list = field(default_factory=list)
    call_ids: list = field(default_factory=list)
    answer: Optional[str] = None
    valid: bool = True
    error: str = ""


@dataclass
class Ledger:
    config: Config
    started: float = field(default_factory=time.perf_counter)
    requests: list = field(default_factory=list)
    tool_events: list = field(default_factory=list)
    output_tokens: int = 0
    usage_complete: bool = True
    turns_committed: int = 0
    tool_calls: int = 0
    lock: object = field(default_factory=threading.Lock, repr=False)

    def check_deadline(self):
        if self.config.wall_seconds and time.perf_counter() - self.started >= self.config.wall_seconds:
            raise BudgetExceeded("wall_budget")

    def allowance(self, requested):
        self.check_deadline()
        cap = self.config.max_total_output_tokens
        remaining = cap - self.output_tokens if cap else requested
        if remaining <= 0:
            raise BudgetExceeded("output_token_budget")
        return min(requested, remaining)

    def record_request(self, event):
        with self.lock:  # dreamr records from the parallel rewrite thread as well
            self.requests.append(event)
            usage = event.get("usage") or {}
            count = usage.get("completion_tokens")
            if isinstance(count, bool) or not isinstance(count, int) or count < 0:
                self.usage_complete = False
                raise ProtocolError("missing_completion_usage")
            self.output_tokens += count
            if self.config.max_total_output_tokens and self.output_tokens > self.config.max_total_output_tokens:
                raise ProtocolError("server_exceeded_output_allowance")

    def record_cancelled(self, event):
        """An abandoned parallel rewrite: no usage is returned, tokens are not counted."""
        with self.lock:
            self.requests.append(event)
            self.usage_complete = False  # Aborted requests do not return completion-token usage.

    def summary(self):
        roles = {}
        for event in self.requests:
            r = roles.setdefault(event["role"], {"requests": 0, "prompt_tokens": 0,
                "completion_tokens": 0, "request_seconds": 0.0})
            r["requests"] += 1
            r["request_seconds"] += event.get("elapsed_s", 0.0)
            for key in ("prompt_tokens", "completion_tokens"):
                r[key] += (event.get("usage") or {}).get(key, 0) or 0
        return {"output_tokens": self.output_tokens, "usage_complete": self.usage_complete,
            "turns_committed": self.turns_committed, "tool_calls": self.tool_calls,
            "roles": roles, "max_total_output_tokens": self.config.max_total_output_tokens,
            "total_token_cap_enabled": bool(self.config.max_total_output_tokens)}


class DreamRAgent:
    def __init__(self, main, draft, tools, schemas, config, result_messages,
                 truncate_history=None, format_feedback=None):
        self.main, self.draft = main, draft
        self.tools, self.schemas, self.config = tools, schemas, config
        self.result_messages = result_messages
        self.truncate_history = truncate_history or (lambda messages, limit: None)
        self.format_feedback = format_feedback

    def run(self, history, images, sample_id=""):
        history = copy.deepcopy(history)
        ledger = Ledger(self.config)
        result = {"sample_id": sample_id, "final_answer": None, "stop_reason": "max_turns",
            "config": asdict(self.config), "steps": [], "requests": ledger.requests,
            "tool_events": ledger.tool_events}
        self.last_result = result
        self.tools.set_input_images(images)
        try:
            for index in range(self.config.max_turns):
                ledger.check_deadline()
                step = {"turn": index, "score": None, "accepted_draft": False}
                result["steps"].append(step)
                if self.config.mode == "specreason":
                    candidate = self.draft.generate(history, self.schemas, ledger, "draft_step")
                    step["candidate"] = copy.deepcopy(candidate.message)
                    score = self.main.score(history, candidate, self.schemas, ledger)
                    step["score"] = score
                    candidate_error = self._invalid(candidate)
                    step["candidate_error"] = candidate_error
                    accepted = score is not None and score >= self.config.threshold and not candidate_error
                    step["accepted_draft"] = accepted
                    if accepted:
                        chosen = candidate
                        step["source"] = "draft"
                    else:
                        # The rejected candidate and the judge suffix NEVER enter H.
                        chosen = self.main.generate(history, self.schemas, ledger, "main_rewrite")
                        step["source"] = "main_rewrite"
                elif self.config.mode == "dreamr":
                    chosen = self._dreamr_turn(history, ledger, step, index)
                else:
                    endpoint = self.main if self.config.mode == "main-only" else self.draft
                    chosen = endpoint.generate(history, self.schemas, ledger, self.config.mode)
                    step["source"] = self.config.mode
                step["committed_message"] = copy.deepcopy(chosen.message)
                ledger.check_deadline()
                error = self._invalid(chosen)
                if error:
                    raise ProtocolError(error)
                if ledger.tool_calls + len(chosen.calls) > self.config.max_tool_calls:
                    raise BudgetExceeded("tool_call_budget")
                history.append(copy.deepcopy(chosen.message))
                ledger.turns_committed += 1
                if chosen.answer is not None:
                    result["final_answer"] = chosen.answer
                    result["stop_reason"] = "answer"
                    break
                if not chosen.calls and self.format_feedback is not None:
                    # Match the existing AgentLoop's protocol recovery. This
                    # committed turn still costs a turn and all of its tokens;
                    # no bare answer is silently treated as a verified final.
                    feedback = self.format_feedback(chosen)
                    step['protocol_feedback'] = feedback
                    history.append({'role': 'user', 'content': [
                        {'type': 'text', 'text': feedback}]})
                for call, call_id in zip(chosen.calls, chosen.call_ids):
                    ledger.check_deadline()
                    started = time.perf_counter()
                    event = {"turn": index, "call_id": call_id,
                        "call": asdict(call), "started_s": started - ledger.started}
                    ledger.tool_calls += 1
                    ledger.tool_events.append(event)
                    try:
                        observation, output_images = self.tools.dispatch(call, images[0])
                        event.update(observation=observation, output_image_sizes=[list(im.size) for im in output_images])
                        history.extend(self.result_messages(call_id, observation, output_images))
                        # Tool execution errors encoded as observations remain visible;
                        # they are not silently retried or counted as new free turns.
                        event["status"] = "returned"
                    except Exception as exc:
                        event.update(status="raised", error=f"{type(exc).__name__}: {exc}")
                        raise InfrastructureError("tool_transport_or_runtime_failure") from exc
                    finally:
                        event["elapsed_s"] = time.perf_counter() - started
                    ledger.check_deadline()
                self.truncate_history(history, self.config.max_image_history)
        except BudgetExceeded as exc:
            result["stop_reason"] = str(exc)
        except ProtocolError as exc:
            result["stop_reason"] = "protocol_error"
            result["error"] = str(exc)
        except InfrastructureError as exc:
            result["stop_reason"] = "infrastructure_error"
            result["error"] = str(exc)
            raise
        finally:
            result.update(history=copy.deepcopy(history), accounting=ledger.summary(),
                total_time=time.perf_counter() - ledger.started)
        return result

    def _dreamr_turn(self, history, ledger, step, index):
        """DREAM-R turn: threshold verification (TBVM) in parallel with Main's own step (FPSR)."""
        if index < self.config.first_main_turns:
            step["source"] = "main_warmup"
            return self.main.generate(history, self.schemas, ledger, "main_warmup")
        candidate = self.draft.generate(history, self.schemas, ledger, "draft_step")
        step["candidate"] = copy.deepcopy(candidate.message)
        candidate_error = self._invalid(candidate)
        step["candidate_error"] = candidate_error
        started = time.perf_counter()
        # Main starts writing this turn itself while it verifies the draft. The
        # rejected candidate and the judge suffix NEVER enter H or the rewrite.
        rewrite = self.main.start_generate(history, self.schemas, ledger, "main_rewrite")
        try:
            probability = self.main.verify(history, candidate, self.schemas, ledger)
        except BaseException:
            rewrite.cancel()
            raise
        step["score"] = probability
        step["verify_seconds"] = time.perf_counter() - started
        accepted = (probability is not None and probability >= self.config.accept_threshold
            and not candidate_error)
        step["accepted_draft"] = accepted
        if accepted:
            step["rewrite_state"] = rewrite.cancel()
            step["source"] = "draft"
            return candidate
        chosen = rewrite.result()
        step["source"] = "main_rewrite"
        step["rewrite_wait_seconds"] = time.perf_counter() - started
        return chosen

    def _invalid(self, turn):
        if not turn.valid:
            return turn.error or "invalid_turn"
        if len(turn.calls) != len(turn.call_ids) or len(set(turn.call_ids)) != len(turn.call_ids):
            return "invalid_tool_call_ids"
        if any(not isinstance(cid, str) or not cid for cid in turn.call_ids):
            return "missing_tool_call_id"
        if turn.calls and turn.answer is not None:
            return "ambiguous_tool_and_answer"
        for call in turn.calls:
            error = self.tools.validate_call(call)
            if error:
                return error
        return ""
